"""
Storage backends for agent-blackbox recordings.

Two built-in stores:

  * JsonlStore  — one append-only .jsonl file per session (default; zero deps;
                  same format as the original demo, human-greppable).
  * SqliteStore — everything in one SQLite database (WAL mode). Better for
                  production single-node deployments and fast listing.

Both are append-only from the recorder's point of view; verification always
recomputes the hash chain, so even a compromised store can't silently edit
history without detection.
"""

from __future__ import annotations

import json
import os
import sqlite3
import threading
from dataclasses import dataclass
from typing import Optional

from .core import verify_events


@dataclass
class SessionInfo:
    session_id: str
    pilot: str
    started_at: str
    n_events: int
    has_error: bool
    has_annotation: bool
    closed: bool


def _summarize(session_id: str, events: list[dict]) -> SessionInfo:
    start = next((e for e in events if e["type"] == "session_start"), None)
    return SessionInfo(
        session_id=session_id,
        pilot=(start or {}).get("payload", {}).get("pilot", "unknown"),
        started_at=(start or {}).get("ts", ""),
        n_events=len(events),
        has_error=any(e["type"] == "error" for e in events),
        has_annotation=any(e["type"] == "annotation" for e in events),
        closed=any(e["type"] == "session_end" for e in events),
    )


class JsonlStore:
    """One append-only JSONL file per session in a directory."""

    def __init__(self, directory: str = "recordings"):
        self.directory = directory
        os.makedirs(directory, exist_ok=True)
        self._lock = threading.Lock()

    def path_for(self, session_id: str) -> str:
        # session ids are generated by us, but guard against path tricks
        safe = os.path.basename(session_id)
        return os.path.join(self.directory, f"{safe}.jsonl")

    def append(self, event: dict) -> None:
        path = self.path_for(event["session_id"])
        line = json.dumps(event, ensure_ascii=False) + "\n"
        with self._lock, open(path, "a", encoding="utf-8") as f:
            f.write(line)
            f.flush()
            os.fsync(f.fileno())

    def load(self, session_id: str) -> list[dict]:
        path = self.path_for(session_id)
        if not os.path.exists(path):
            raise FileNotFoundError(f"No recording for session {session_id!r} in {self.directory}")
        events = []
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    events.append(json.loads(line))
        return events

    def list_sessions(self) -> list[SessionInfo]:
        infos = []
        for name in sorted(os.listdir(self.directory)):
            if not name.endswith(".jsonl"):
                continue
            sid = name[: -len(".jsonl")]
            try:
                infos.append(_summarize(sid, self.load(sid)))
            except Exception:
                continue
        infos.sort(key=lambda i: i.started_at, reverse=True)
        return infos

    def verify(self, session_id: str) -> tuple[bool, str]:
        return verify_events(self.load(session_id))


class SqliteStore:
    """All sessions in one SQLite database.

    Events are stored as their canonical JSON, so hashing/verification is
    identical to the JSONL store.
    """

    def __init__(self, db_path: str = "blackbox.db"):
        self.db_path = db_path
        parent = os.path.dirname(os.path.abspath(db_path))
        os.makedirs(parent, exist_ok=True)
        self._lock = threading.Lock()
        self._local = threading.local()
        with self._conn() as conn:
            conn.execute("PRAGMA journal_mode=WAL")
            conn.execute(
                """CREATE TABLE IF NOT EXISTS events (
                    session_id TEXT NOT NULL,
                    seq        INTEGER NOT NULL,
                    type       TEXT NOT NULL,
                    ts         TEXT NOT NULL,
                    event_json TEXT NOT NULL,
                    PRIMARY KEY (session_id, seq)
                )"""
            )
            conn.execute(
                "CREATE INDEX IF NOT EXISTS idx_events_type ON events (session_id, type)"
            )

    def _conn(self) -> sqlite3.Connection:
        conn = getattr(self._local, "conn", None)
        if conn is None:
            conn = sqlite3.connect(self.db_path)
            self._local.conn = conn
        return conn

    def append(self, event: dict) -> None:
        with self._lock:
            conn = self._conn()
            conn.execute(
                "INSERT INTO events (session_id, seq, type, ts, event_json) VALUES (?,?,?,?,?)",
                (
                    event["session_id"], event["seq"], event["type"], event["ts"],
                    json.dumps(event, ensure_ascii=False),
                ),
            )
            conn.commit()

    def load(self, session_id: str) -> list[dict]:
        rows = self._conn().execute(
            "SELECT event_json FROM events WHERE session_id=? ORDER BY seq",
            (session_id,),
        ).fetchall()
        if not rows:
            raise FileNotFoundError(f"No recording for session {session_id!r} in {self.db_path}")
        return [json.loads(r[0]) for r in rows]

    def list_sessions(self) -> list[SessionInfo]:
        sids = [r[0] for r in self._conn().execute(
            "SELECT DISTINCT session_id FROM events"
        ).fetchall()]
        infos = [_summarize(sid, self.load(sid)) for sid in sids]
        infos.sort(key=lambda i: i.started_at, reverse=True)
        return infos

    def verify(self, session_id: str) -> tuple[bool, str]:
        return verify_events(self.load(session_id))


def open_store(directory: Optional[str] = None, db: Optional[str] = None):
    """Resolve a store from CLI/env style options. `db` wins over `directory`."""
    if db:
        return SqliteStore(db)
    return JsonlStore(directory or os.environ.get("BLACKBOX_DIR", "recordings"))
